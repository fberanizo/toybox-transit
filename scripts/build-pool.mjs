#!/usr/bin/env node
// Build the prevalidated level pool shipped with the game: levels/pool-g<V>.json
// Stores seeds only (plus measured band and score); the game re-constructs each level from its seed with the
// same generator version, so the pool stays tiny and every entry is reproducible.
// Usage: node scripts/build-pool.mjs [--per-band=120]

import { writeFileSync, mkdirSync } from 'node:fs';
import { construct, evaluate, makeSeed, BANDS, GEN_VERSION, RECIPES } from '../src/core/generator.js';
import { isNearDuplicate, canonicalHash } from '../src/core/similarity.js';

const arg = (k, d) => (process.argv.find((a) => a.startsWith(`--${k}=`)) || '').split('=')[1] ?? d;
const PER = +arg('per-band', 120);

// Which generation recipes tend to produce which measured band (from validation runs).
const SOURCES = RECIPES;

const pool = Object.fromEntries(BANDS.map((b) => [b, []]));
const accepted = Object.fromEntries(BANDS.map((b) => [b, []]));
const hashes = new Set();
const counters = Object.fromEntries(BANDS.map((b) => [b, 0]));
let tried = 0, dups = 0;
const t0 = performance.now();

for (let round = 0; round < 400 && BANDS.some((b) => pool[b].length < PER); round++) {
    for (const genBand of BANDS) {
        for (let k = 0; k < 40; k++) {
            const seed = makeSeed(genBand, counters[genBand]++);
            tried++;
            const c = construct(seed);
            if (c.fail) continue;
            const e = evaluate(c.level);
            if (!e.ok || pool[e.band].length >= PER) continue;
            if (!SOURCES[e.band].includes(genBand)) continue;
            const h = canonicalHash(c.level);
            if (hashes.has(h) || accepted[e.band].some((o) => isNearDuplicate(o, c.level))) { dups++; continue; }
            hashes.add(h);
            accepted[e.band].push(c.level);
            pool[e.band].push({ seed, score: e.score });
        }
    }
}

const out = { genVersion: GEN_VERSION, built: new Date().toISOString(), perBand: PER, levels: pool };
mkdirSync('levels', { recursive: true });
writeFileSync(`levels/pool-g${GEN_VERSION}.json`, JSON.stringify(out));
// Also as an ES module so the no-build game can import it directly.
writeFileSync(`src/levels/pool.js`, `// Generated by scripts/build-pool.mjs — do not edit.\nexport const POOL = ${JSON.stringify(out)};\n`);
console.log(JSON.stringify({
    seconds: +((performance.now() - t0) / 1000).toFixed(1), tried, nearDuplicatesSkipped: dups,
    counts: Object.fromEntries(BANDS.map((b) => [b, pool[b].length]))
}));
